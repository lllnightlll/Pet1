CREATE TABLE IF NOT EXISTS CUSTOMERS (
    customer_id INT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    address VARCHAR(255) NOT NULL,
    phone VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    inn VARCHAR(255) UNIQUE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT now()
);
        
CREATE TABLE IF NOT EXISTS SUPPLIERS (
    supplier_id INT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    address VARCHAR(255) NOT NULL,
    phone VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    inn VARCHAR(255) UNIQUE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
);

CREATE TABLE IF NOT EXISTS ORDERS (
    order_id INT PRIMARY KEY,
    customer_id INT NOT NULL,
    store_id INT NOT NULL,
    order_date DATE NOT NULL,
    total_sum DECIMAL(10, 2) NOT NULL,
    discount_pct DECIMAL(10, 2) DEFAULT 0,
    discount_amount DECIMAL(10, 2) DEFAULT 0
);

CREATE TABLE IF NOT EXISTS ORDER_ITEMS (
    order_id INT,
    product_id INT,
    quantity DECIMAL(10, 2) NOT NULL,
    price DECIMAL(10, 2) NOT NULL,
    discount_pct DECIMAL(10, 2) DEFAULT 0,
    PRIMARY KEY (order_id, product_id)
);

CREATE TABLE IF NOT EXISTS PRODUCT_PRICE_HISTORY (
    price_id INT PRIMARY KEY,
    product_id INT NOT NULL,
    supplier_id INT NOT NULL,
    price DECIMAL(10, 2) NOT NULL,
    valid_from DATE NOT NULL,
    valid_to DATE
);

CREATE TABLE IF NOT EXISTS DISCOUNT_RULES (
    rule_id INT PRIMARY KEY,
    customer_id INT UNIQUE NOT NULL,
    discount_pct DECIMAL(10, 2) NOT NULL DEFAULT 0,
    valid_from DATE NOT NULL,
    valid_to DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);  

CREATE TABLE IF NOT EXISTS SUPPLIES (
    supply_id INT PRIMARY KEY,
    supplier_id INT NOT NULL,
    product_id INT NOT NULL,
    quantity DECIMAL(10, 2) NOT NULL,
    price_per_unit DECIMAL(10, 2) NOT NULL,
    supply_date DATE NOT NULL,
    expiry_date DATE,
    document_number VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS SUPPLIES_AUDIT (
    audit_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supply_id INT,
    supplier_id INT NOT NULL,
    product_id INT NOT NULL,
    quantity DECIMAL(10, 2) NOT NULL,
    price_per_unit DECIMAL(10, 2) NOT NULL,
    supply_date DATE NOT NULL,
    expiry_date DATE DEFAULT NULL,
    document_number VARCHAR(255) NOT NULL,
    operation VARCHAR(255) NOT NULL,
    changed_by VARCHAR(255) NOT NULL,
    changed_at TIMESTAMP NOT NULL DEFAULT now()
    );
   
CREATE TABLE IF NOT EXISTS WAREHOUSE_STOCK (
    product_id INT PRIMARY KEY,
    quantity DECIMAL(10, 2) NOT NULL,
    last_updated TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS PLAN_STOCK (
    product_id INT PRIMARY KEY,
    plan_qty DECIMAL(10, 2) NOT NULL DEFAULT 0
);
	
CREATE TABLE IF NOT EXISTS CATEGORIES (
    category_id INT PRIMARY KEY,
    parent_id INT DEFAULT NULL,
    name VARCHAR(255) NOT NULL
);
	
CREATE TABLE IF NOT EXISTS PRODUCTS (
    product_id INT PRIMARY KEY,
    category_id INT NOT NULL,
    name VARCHAR(255) NOT NULL
        CONSTRAINT chk_products_name_capital CHECK (name ~ '^[[:upper:]]'),
    unit VARCHAR(255) NOT NULL,
    barcode VARCHAR(255) UNIQUE NOT NULL,
    shelf_life_days INT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT now()
);
   
CREATE TABLE IF NOT EXISTS STORES (
    store_id INT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    address VARCHAR(255) NOT NULL,
    phone VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS STORE_STOCK (
    product_id INT,
    store_id INT NOT NULL,
    quantity DECIMAL(10, 2) NOT NULL,
    last_updated TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (product_id, store_id)
);
   
CREATE TABLE IF NOT EXISTS MOVEMENTS (
    movement_id INT PRIMARY KEY,
    product_id INT NOT NULL,
    store_id INT NOT NULL,
    movement_type VARCHAR(255) NOT NULL,
    quantity DECIMAL(10, 2) NOT NULL,
    movement_date DATE NOT NULL,
    document_number VARCHAR(255) NOT NULL
);



